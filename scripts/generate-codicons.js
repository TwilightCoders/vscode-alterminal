#!/usr/bin/env node
// Parses @vscode/codicons' CSV manifest into a TypeScript array.
// Run during `compile` so src/generated/codicons.ts stays in sync with
// whatever codicon version we're shipping.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const csvPath = path.join(root, 'node_modules', '@vscode', 'codicons', 'dist', 'codicon.csv');
const outDir = path.join(root, 'src', 'generated');
const outFile = path.join(outDir, 'codicons.ts');

if (!fs.existsSync(csvPath)) {
  console.error(`codicon.csv not found at ${csvPath} — did you run npm install?`);
  process.exit(1);
}

const csv = fs.readFileSync(csvPath, 'utf8');
const lines = csv.split('\n').filter(Boolean);
// Strip header row ("short_name,character,unicode")
lines.shift();

const names = lines
  .map((line) => line.split(',')[0].trim())
  .filter((name) => name.length > 0 && /^[a-z0-9-]+$/.test(name));

names.sort();

fs.mkdirSync(outDir, { recursive: true });
const ts =
  '// Auto-generated by scripts/generate-codicons.js. Do not edit.\n' +
  `// Source: @vscode/codicons (${names.length} icons).\n` +
  `export const CODICON_NAMES: readonly string[] = ${JSON.stringify(names, null, 2)} as const;\n`;
fs.writeFileSync(outFile, ts);

console.log(`Wrote ${names.length} codicon names to ${path.relative(root, outFile)}`);
