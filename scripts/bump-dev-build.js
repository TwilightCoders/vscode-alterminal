#!/usr/bin/env node
// Increments .vscode/dev-counter and writes src/generated/buildInfo.ts.
// Run as a preLaunchTask dependency so each F5 gets a unique build number.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const counterFile = path.join(root, '.vscode', 'dev-counter');
const outDir = path.join(root, 'src', 'generated');
const outFile = path.join(outDir, 'buildInfo.ts');

let counter = 1;
try { counter = parseInt(fs.readFileSync(counterFile, 'utf8'), 10) + 1; } catch {}
fs.writeFileSync(counterFile, String(counter));

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, `// Auto-generated by bump-dev-build.js. Do not edit.\nexport const DEV_BUILD_NUMBER = ${counter};\n`);

console.log(`Dev build #${counter}`);
