#!/usr/bin/env node
// Manages the dev-build counter (.vscode/dev-counter) and regenerates
// src/generated/buildInfo.ts so the running build can report its number.
//
// Modes:
//   (default)        Increment + persist + regenerate buildInfo. Used by the
//                    F5 preLaunchTask, where every launch gets a fresh number.
//   --peek           Regenerate buildInfo with the *next* number and print that
//                    number, but DO NOT persist the counter. Lets a caller bake
//                    the number into a build before knowing it will succeed.
//   --commit <n>     Persist <n> as the counter. A caller runs this only after
//                    a build artifact actually exists, so a failed build never
//                    burns a number.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const counterFile = path.join(root, '.vscode', 'dev-counter');
const outDir = path.join(root, 'src', 'generated');
const outFile = path.join(outDir, 'buildInfo.ts');

const mode = process.argv[2];

const readCounter = () => {
  try { return parseInt(fs.readFileSync(counterFile, 'utf8'), 10) || 0; } catch { return 0; }
};
const persist = (n) => fs.writeFileSync(counterFile, String(n));
const writeBuildInfo = (n) => {
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outFile, `// Auto-generated by bump-dev-build.js. Do not edit.\nexport const DEV_BUILD_NUMBER = ${n};\n`);
};

if (mode === '--commit') {
  const n = parseInt(process.argv[3], 10);
  if (!Number.isInteger(n)) { console.error('--commit requires an integer'); process.exit(1); }
  persist(n);
  process.exit(0);
}

const next = readCounter() + 1;
writeBuildInfo(next);

if (mode === '--peek') {
  process.stdout.write(String(next)); // no trailing newline — easy to capture
} else {
  persist(next);
  console.log(`Dev build #${next}`);
}
